"""
image_tools/effects_menu.py
===========================

This is the ONLY file you edit to add a new image effect.

The file defines a single dictionary, ``EFFECTS``. Every entry
describes one effect: which group it belongs to, what to show as a
tooltip, which function performs the work, and which parameters the
user should be able to change.

The image screen reads this dictionary and:

* builds the group menu,
* builds the effect menu,
* draws one widget per parameter,
* calls the function with the chosen values,
* shows the result.

How to add an effect
--------------------
1. Write a pure function in ``operations.py`` (or ``drawing.py``).
2. Add one entry to ``EFFECTS`` below.

That is all. Nothing else changes anywhere in the project.
"""

